export function iconSvg(name, size = 18, className = 'lucide') {
  const inner = paths[name] || paths.sparkles;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round" class="${className}" aria-hidden="true">${inner}</svg>`;
}

export function iconEl(name, size = 18, className = 'lucide') {
  const wrap = document.createElement('span');
  wrap.className = 'ico-wrap';
  wrap.innerHTML = iconSvg(name, size, className);
  return wrap.firstElementChild;
}

